#!/usr/bin/env python3
"""Build a VoidGram-only Arabic dictionary without changing the AyuGram build.

Run from repository root: python3 tools/build_voidgram_translations.py
"""
from __future__ import annotations

import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
BASE = ROOT / "locales"
PLACEHOLDERS = re.compile(r"%(?:\d+\$)?[@dfsu]")

def check_placeholders(source: str, target: str) -> None:
    if PLACEHOLDERS.findall(source) != PLACEHOLDERS.findall(target):
        raise ValueError(f"Changed printf placeholders: {source!r}")

def load_base() -> dict[str, str]:
    result: dict[str, str] = {}
    for path in sorted(BASE.glob("ar-*.json")):
        for key, value in json.loads(path.read_text(encoding="utf-8")).items():
            if not isinstance(key, str) or not isinstance(value, str) or not value.strip():
                raise ValueError(f"Invalid entry in {path}: {key!r}")
            check_placeholders(key, value)
            if key in result and result[key] != value:
                raise ValueError(f"Conflicting translations for {key!r}")
            result[key] = value
    return result

# Some references really are to AyuGram Desktop or plugin source repositories.
# Never rename those names, even when the enclosing sentence says VoidGram.
PROTECTED = ("AyuGram Desktop", "AyuGram-IOS", "AyuGramm-IOS",
             "AyuGramm-Plugins", "AyuGramm", "ayugram.db")

def rename_app_brand(value: str) -> str:
    tokens = {f"__VG_PROTECTED_{i}__": literal for i, literal in enumerate(PROTECTED)}
    for token, literal in tokens.items():
        value = value.replace(literal, token)
    value = re.sub(r"(?<![A-Za-z])AyuGram(?![A-Za-z])", "VoidGram", value)
    for token, literal in tokens.items():
        value = value.replace(token, literal)
    return value

def build() -> dict[str, str]:
    original = load_base()
    result = dict(original)
    aliases = 0
    for key, value in original.items():
        new_key = rename_app_brand(key)
        if new_key != key and new_key not in result:
            new_value = rename_app_brand(value)
            check_placeholders(new_key, new_value)
            result[new_key] = new_value
            aliases += 1
    specific_count = 0
    for name in ("voidgram-extra.json", "voidgram-27-8-2.json"):
        extra_path = BASE / name
        extra = json.loads(extra_path.read_text(encoding="utf-8"))
        for key, value in extra.items():
            if not isinstance(key, str) or not isinstance(value, str) or not value.strip():
                raise ValueError(f"Invalid VoidGram translation in {name}: {key!r}")
            check_placeholders(key, value)
            result[key] = value
        specific_count += len(extra)
    print(f"VoidGram dictionary: {len(original)} base + {aliases} renamed aliases + "
          f"{specific_count} specific entries = {len(result)} unique keys")
    return result

def main() -> None:
    merged = build()
    raw = json.dumps(merged, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    lines = ["    " + ", ".join(f"0x{x:02x}" for x in raw[i:i+16]) + ","
             for i in range(0, len(raw), 16)]
    dest = ROOT / "src" / "generated_voidgram_ar.h"
    dest.write_text("// Generated by tools/build_voidgram_translations.py; do not edit.\n"
                    "static const unsigned char VG_AR_BYTES[] = {\n"
                    + "\n".join(lines) + "\n};\n", encoding="utf-8")
    print(f"Wrote {dest.relative_to(ROOT)} ({len(raw)} UTF-8 bytes)")

if __name__ == "__main__":
    main()
